// tools/build-preview.mjs
// Generates preview.html (single file, works when opened via file://) from
// index.html + every ES module under src/. No hand-bundling any more:
//   node tools/build-preview.mjs
// How: each module becomes a base64 data: URL registered in the page's
// import map under a bare "@td/<path>" specifier; relative imports inside
// modules are rewritten to those specifiers, and JSON fetched at runtime
// (map_01.json) is inlined so no fetch() is needed under file://.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const srcDir = path.join(root, 'src');

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((d) =>
    d.isDirectory() ? walk(path.join(dir, d.name)) : d.name.endsWith('.js') ? [path.join(dir, d.name)] : []);
}

const imports = {};
for (const file of walk(srcDir)) {
  const rel = path.relative(root, file).split(path.sep).join('/');
  let code = fs.readFileSync(file, 'utf8');
  code = code.replace(/(from\s+|import\s*\(\s*|import\s+)(['"])(\.{1,2}\/[^'"]+)\2/g, (m, pre, q, spec) => {
    const target = path.relative(root, path.resolve(path.dirname(file), spec)).split(path.sep).join('/');
    return `${pre}${q}@td/${target}${q}`;
  });
  // inline fetched JSON data files
  code = code.replace(/await fetch\((\w+)\)\.then\(\(r\) => r\.json\(\)\)/g, (m, varName) => {
    const decl = code.match(new RegExp(`const ${varName} = ['"]([^'"]+)['"]`));
    if (!decl) return m;
    const json = fs.readFileSync(path.join(root, decl[1]), 'utf8');
    return `(${json.trim()})`;
  });
  imports[`@td/${rel}`] = 'data:text/javascript;base64,' + Buffer.from(code, 'utf8').toString('base64');
}

let html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const mapMatch = html.match(/<script type="importmap">([\s\S]*?)<\/script>/);
if (!mapMatch) throw new Error('index.html has no importmap');
const baseMap = JSON.parse(mapMatch[1]);
baseMap.imports = { ...baseMap.imports, ...imports };
html = html.replace(mapMatch[0], `<script type="importmap">\n${JSON.stringify(baseMap)}\n</script>`);
html = html.replace(/<script type="module" src="\.\/src\/render\/main\.js"><\/script>/,
  `<script type="module">import '@td/src/render/main.js';</script>`);
html = html.replace('<head>', '<head>\n<!-- GENERATED by tools/build-preview.mjs from index.html + src/ -- do not edit by hand -->');
fs.writeFileSync(path.join(root, 'preview.html'), html);
console.log('preview.html written,', Object.keys(imports).length, 'modules,', (html.length / 1024).toFixed(0), 'KB');
